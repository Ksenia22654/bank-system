-- Система автоматизации работы банка с физическими лицами.
-- Скрипт создаёт структуру базы данных (Java DB) и заполняет её начальными данными.
-- Все денежные суммы хранятся в валюте счёта; курс валюты указан к базовой валюте (RUB).

-- ===== Справочники =====

CREATE TABLE roles (
    code   VARCHAR(20) NOT NULL PRIMARY KEY,
    title  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE operation_types (
    code   VARCHAR(20) NOT NULL PRIMARY KEY,
    title  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE loan_statuses (
    code   VARCHAR(20) NOT NULL PRIMARY KEY,
    title  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE currencies (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  CHAR(3)       NOT NULL UNIQUE,
    name  VARCHAR(50)   NOT NULL,
    rate  DECIMAL(12,4) NOT NULL CONSTRAINT chk_currency_rate CHECK (rate > 0)
);

CREATE TABLE account_types (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(50)  NOT NULL UNIQUE,
    annual_rate  DECIMAL(5,2) NOT NULL CONSTRAINT chk_type_rate CHECK (annual_rate >= 0)
);

-- ===== Основные таблицы =====

CREATE TABLE clients (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name      VARCHAR(50)  NOT NULL,
    first_name     VARCHAR(50)  NOT NULL,
    middle_name    VARCHAR(50),
    birth_date     DATE         NOT NULL,
    passport_no    VARCHAR(20)  NOT NULL UNIQUE,
    phone          VARCHAR(20)  NOT NULL,
    email          VARCHAR(100),
    address        VARCHAR(200) NOT NULL,
    registered_on  DATE         NOT NULL
);

CREATE TABLE users (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login          VARCHAR(30)  NOT NULL UNIQUE,
    password_hash  VARCHAR(200) NOT NULL,
    role_code      VARCHAR(20)  NOT NULL REFERENCES roles (code),
    client_id      INT REFERENCES clients (id) ON DELETE CASCADE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE accounts (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no   VARCHAR(20)   NOT NULL UNIQUE,
    client_id    INT           NOT NULL REFERENCES clients (id),
    type_id      INT           NOT NULL REFERENCES account_types (id),
    currency_id  INT           NOT NULL REFERENCES currencies (id),
    balance      DECIMAL(15,2) NOT NULL DEFAULT 0 CONSTRAINT chk_balance CHECK (balance >= 0),
    opened_on    DATE          NOT NULL,
    closed_on    DATE
);

CREATE TABLE loans (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   INT           NOT NULL REFERENCES accounts (id),
    amount       DECIMAL(15,2) NOT NULL CONSTRAINT chk_loan_amount CHECK (amount > 0),
    annual_rate  DECIMAL(5,2)  NOT NULL CONSTRAINT chk_loan_rate CHECK (annual_rate >= 0),
    term_months  INT           NOT NULL CONSTRAINT chk_loan_term CHECK (term_months > 0),
    applied_on   DATE          NOT NULL,
    issued_on    DATE,
    status_code  VARCHAR(20)   NOT NULL REFERENCES loan_statuses (code)
);

CREATE TABLE operations (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code        VARCHAR(20)  NOT NULL REFERENCES operation_types (code),
    from_account_id  INT REFERENCES accounts (id),
    to_account_id    INT REFERENCES accounts (id),
    debit_amount     DECIMAL(15,2),
    credit_amount    DECIMAL(15,2),
    loan_id          INT REFERENCES loans (id),
    performed_at     TIMESTAMP    NOT NULL,
    performed_by     INT REFERENCES users (id) ON DELETE SET NULL,
    description      VARCHAR(200),
    CONSTRAINT chk_operation_side CHECK (from_account_id IS NOT NULL OR to_account_id IS NOT NULL)
);

CREATE INDEX idx_operations_date ON operations (performed_at);

